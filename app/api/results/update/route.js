import { NextResponse } from "next/server";
import { FieldValue } from "firebase-admin/firestore";
import { db } from "@/lib/firebase-admin";
import { getCurrentUser } from "@/lib/auth-session";
import { isUserAdmin } from "@/utils/admins";

export async function POST(request) {
  try {
    // 1. Admin Authentication & Authorization Check
    const user = await getCurrentUser();
    if (!user) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const isAdmin = Boolean(isUserAdmin(user.mobile) || user.is_admin === true);
    if (!isAdmin) {
      return NextResponse.json({ error: "Admin privilege required" }, { status: 403 });
    }

    const body = await request.json();
    const { name, result, time, message, updateType } = body;

    if (!name) {
      return NextResponse.json(
        { error: "Market name is required" },
        { status: 400 }
      );
    }

    // 2. Main Market Result Update in Firestore
    const docRef = db.collection("market_results").doc(name);

    const updatePayload = {
  name,
  updatedAt: FieldValue.serverTimestamp(),
};

if (updateType === "result") {
  updatePayload.result = result?.trim() || "140-55-140";
  updatePayload.time = time?.trim() || "";
}

if (updateType === "message") {
  updatePayload.message = message?.trim() || "";
}

await docRef.set(updatePayload, { merge: true });

    // 3. Auto-Post Banner to Guessing Forum (Only when result is updated)
    if (
  updateType === "result" &&
  result &&
  result.trim() !== ""
) {
      const autoGeneratedPostText = 
`!※! LIVE RESULTS !※!

✹ ✧ ${name.toUpperCase()} ✧ ✹
─ ─ ─ ─ ─ ─ ─ ─
${result.trim()}
─ ─ ─ ─ ─ ─ ─ ─
◉ !❇!✶! !✶!❇! ◉`;

      await db.collection("guessing_posts").add({
        userId: user.uid || "ADMIN",
        username: user.username || user.name || "ADMIN",
        guess: autoGeneratedPostText,
        quotes: [],
        createdAt: new Date(),
        isAutoResult: true
      });
    }

    const savedDoc = await docRef.get();
const savedData = savedDoc.data();

return NextResponse.json({
  success: true,
  result: {
    name: savedData.name || name,
    result: savedData.result || "",
    time: savedData.time || "",
    message: savedData.message || "",
  },
});
  } catch (error) {
    console.error("Update result error:", error);
    return NextResponse.json(
      { error: error.message },
      { status: 500 }
    );
  }
}
